/**
 * Families — 6.2, 6.6 and the member list of 5.3.
 *
 * The server owns membership and nothing else about a family. There is no column for its name:
 * 2.2 keeps that inside the journal as an ordinary encrypted entity, and a display name on a
 * server row would be exactly the metadata leak the whole scheme is arranged to avoid.
 */
import type { FastifyInstance } from "fastify";

import type { Db } from "../db.ts";
import type { ServerContext } from "../context.ts";
import { ApiError, forbidden, notFound } from "../errors.ts";
import { body, identifierField, uuidField } from "./fields.ts";

/**
 * 6.6 and 6.7: leaving, being removed and having a device revoked all end with the same server
 * act — every device of that account stops being able to reach the family, at once. Revocation
 * does not touch the family key, and the document is blunt about why that matters: the key sits in
 * the IndexedDB of the device that just lost its token, so the owner's rotation is the part that
 * actually closes the door, and until it happens the screen says so.
 */
export function revokeAccountDevices(db: Db, accountId: string, now: number): void {
  db.prepare(
    "UPDATE device SET revoked_at = ?, refresh_token_hash = NULL, refresh_expires_at = NULL" +
      " WHERE account_id = ? AND revoked_at IS NULL",
  ).run(now, accountId);
}

export function registerFamilyRoutes(app: FastifyInstance, context: ServerContext): void {
  app.post(
    "/v1/families",
    {
      schema: {
        // `rotationId` is required, not optional. 2.2 gives every `epoch` row a `rotationId`
        // generated by the owner's device, and 5.5 has an out-of-rotation wrap carry "the
        // `rotationId` that produced the epoch in force" — for epoch `1` that can only be a value
        // the creating device chose here. Letting it be omitted would leave the first epoch of a
        // family unable to hand a wrap to a device bound later, which is the one case 5.5 ends on.
        body: body(
          { familyId: uuidField, memberId: identifierField, rotationId: uuidField },
          ["familyId", "memberId", "rotationId"],
        ),
      },
    },
    async (request, reply) => {
      const auth = context.authenticate(request);
      const input = request.body as { familyId: string; memberId: string; rotationId: string };
      const existing = context.db
        .prepare("SELECT member_id FROM member WHERE account_id = ? AND removed_at IS NULL")
        .get(auth.accountId);
      if (existing !== undefined) {
        throw new ApiError(409, "already_in_family", "this account already belongs to a family");
      }
      const clash = context.db
        .prepare("SELECT family_id FROM family WHERE family_id = ?")
        .get(input.familyId);
      if (clash !== undefined) {
        // Its own code, not the one above: the caller is in no family and the remedy is another
        // identifier, which is the opposite of what "you already have a family" tells them to do.
        throw new ApiError(409, "family_exists", "this family identifier is taken");
      }
      const now = context.now();
      context.db.transaction(() => {
        context.db
          .prepare(
            "INSERT INTO family (family_id, created_at, key_epoch, max_key_epoch, owner_member_id)" +
              " VALUES (?, ?, 1, 1, ?)",
          )
          .run(input.familyId, now, input.memberId);
        // 6.2: the family starts at epoch `1`, active from the first moment, with its own `seq`
        // counter at zero — 2.2 reserves `0` for the empty cursor, so the first envelope gets `1`.
        context.db
          .prepare(
            "INSERT INTO epoch (family_id, key_epoch, seq_counter, state, rotation_id)" +
              " VALUES (?, 1, 0, 'active', ?)",
          )
          .run(input.familyId, input.rotationId);
        context.db
          .prepare(
            "INSERT INTO member (member_id, family_id, account_id, role, joined_at)" +
              " VALUES (?, ?, ?, 'owner', ?)",
          )
          .run(input.memberId, input.familyId, auth.accountId, now);
      })();
      return reply.code(201).send({
        familyId: input.familyId,
        keyEpoch: 1,
        memberId: input.memberId,
        role: "owner",
      });
    },
  );

  app.get("/v1/families/me", async (request) => {
    const auth = context.authenticate(request);
    const membership = context.requireMembership(auth);
    const staging = context.stagingEpoch(membership.familyId);
    return {
      familyId: membership.familyId,
      keyEpoch: membership.keyEpoch,
      memberId: membership.memberId,
      role: membership.role,
      ownerMemberId: membership.ownerMemberId,
      // 7.1 names the unfinished rotation as something the user must be able to see: the server
      // can hold a family in the old epoch indefinitely, and the only answer is that the state is
      // visible and does not go away by itself.
      rotation:
        staging === undefined
          ? null
          : {
              keyEpoch: staging.key_epoch,
              rotationId: staging.rotation_id,
              rotatingDeviceId: staging.rotating_device_id,
              freezeSeq: staging.freeze_seq,
              startedAt: staging.rotation_started_at,
              lastProgressAt: staging.last_progress_at,
            },
    };
  });

  app.get(
    "/v1/families/:familyId/members",
    { schema: { params: body({ familyId: uuidField }, ["familyId"]) } },
    async (request) => {
      const auth = context.authenticate(request);
      const { familyId } = request.params as { familyId: string };
      const membership = context.requireFamily(auth, familyId);
    // 5.3: the joining device checks the inviter's self-declared role against this list. The list
    // is one of two independent sources, and the document says plainly that neither is trusted
    // alone — the box is written by the inviter, the list is kept by the server.
      const rows = context.db
        .prepare(
          "SELECT member_id, role, joined_at, removed_at FROM member WHERE family_id = ?" +
            " ORDER BY joined_at, member_id",
        )
        .all(membership.familyId) as {
        member_id: string;
        role: string;
        joined_at: number;
        removed_at: number | null;
      }[];
      return {
        members: rows.map((row) => ({
          memberId: row.member_id,
          role: row.role,
          joinedAt: row.joined_at,
          removedAt: row.removed_at,
        })),
      };
    },
  );

  app.delete(
    "/v1/families/:familyId/members/:memberId",
    {
      schema: {
        params: body({ familyId: uuidField, memberId: identifierField }, ["familyId", "memberId"]),
      },
    },
    async (request) => {
      const auth = context.authenticate(request);
      const { familyId, memberId } = request.params as { familyId: string; memberId: string };
      const membership = context.requireOwner(context.requireFamily(auth, familyId));
      if (memberId === membership.memberId) {
        throw forbidden("forbidden", "the owner cannot be removed from the family");
      }
      const target = context.db
        .prepare(
          "SELECT member_id, account_id FROM member WHERE family_id = ? AND member_id = ?" +
            " AND removed_at IS NULL",
        )
        .get(membership.familyId, memberId) as
        | { member_id: string; account_id: string }
        | undefined;
      if (target === undefined) throw notFound("no such member in this family");
      const now = context.now();
      context.db.transaction(() => {
        // Scoped by the family, because since migration 2 the key of a member is the pair: the
        // identifier is chosen by the client and is only unique inside its own family.
        context.db
          .prepare("UPDATE member SET removed_at = ? WHERE family_id = ? AND member_id = ?")
          .run(now, membership.familyId, target.member_id);
        revokeAccountDevices(context.db, target.account_id, now);
      })();
      // 6.6: the rotation that follows is mandatory and is the owner's device's job, not the
      // server's. The server cannot start it — it has no key — and must not pretend it did.
      return { memberId: target.member_id, removedAt: now, rotationRequired: true };
    },
  );

  app.post(
    "/v1/families/:familyId/leave",
    { schema: { params: body({ familyId: uuidField }, ["familyId"]) } },
    async (request) => {
      const auth = context.authenticate(request);
      const { familyId } = request.params as { familyId: string };
      const membership = context.requireFamily(auth, familyId);
      if (membership.role === "owner") {
        // Handing the owner role to someone else is excluded from this plan by section 1, so an
        // owner who leaves would leave a family no one can rotate or invite into. The owner's exit
        // is account deletion (6.8), not this route.
        throw forbidden("forbidden", "the owner cannot leave the family");
      }
      const now = context.now();
      context.db.transaction(() => {
        context.db
          .prepare("UPDATE member SET removed_at = ? WHERE family_id = ? AND member_id = ?")
          .run(now, membership.familyId, membership.memberId);
        revokeAccountDevices(context.db, auth.accountId, now);
      })();
      return { memberId: membership.memberId, removedAt: now, rotationRequired: true };
    },
  );
}
