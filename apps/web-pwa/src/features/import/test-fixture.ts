function quote(field: string): string {
  return `"${field.replaceAll('"', '""')}"`;
}

/** Текст файла так, как его пишет банк: каждое поле в кавычках, строки через CRLF. */
export function sampleStatementText(): string {
  const lines = [SAMPLE_STATEMENT_HEADER, ...ROWS].map((row) => row.map(quote).join(";"));
  return `${lines.join("\r\n")}\r\n`;
}

export function sampleStatementBytes(): Uint8Array {
  return encodeWindows1251(sampleStatementText());
}

